import assert from 'node:assert/strict';
import path from 'node:path';
import { createRequire } from 'node:module';
import { createServer } from 'vite';
const require = createRequire(import.meta.url);
const { chromium } = require(process.argv[2] || 'playwright');
const server = await createServer({ server: { host:'127.0.0.1',port:0 }, plugins:[{ name:'ai-audit',configureServer(s){s.middlewares.use('/__ai_audit',async (_req,res)=>{res.setHeader('Content-Type','text/html');res.end(await s.transformIndexHtml('/__ai_audit','<html><body><div id="root"></div><script type="module" src="/test/ai-tools-harness.jsx"></script></body></html>'));});} }] });
let browser;
try {
  await server.listen();
  browser=await chromium.launch({headless:true, ...(process.env.H3_TEST_BROWSER_CHANNEL ? {channel:process.env.H3_TEST_BROWSER_CHANNEL} : {})});
  const page=await browser.newPage({viewport:{width:1500,height:1000}});
  const errors=[]; page.on('pageerror',e=>errors.push(e.message));
  await page.addInitScript(()=>{
    window.studio={getAiToolsState:async()=>({ready:true,models:{segment:true,understand:true,enhance:true,"image-enhance":true,interpolate:true}}),onAiToolProgress:()=>()=>{},getPathForFile:f=>'C:/audit/'+f.name,runAiTool:async p=>{window.auditPayload=p;if(window.hold)await new Promise(resolve=>window.finish=resolve);if(p.kind==='image-enhance')return {ok:true,resultPath:'C:/audit/upscaled.png',previewUrl:document.querySelector('.ai-result-preview').src};if(p.kind==='segment')return {ok:true,resultPath:'C:/audit/result.png',previewUrl:document.querySelector('.ai-selection-image img').src};return {ok:true,text:window.answer||'一朵花'};}};
  });
  await page.goto(`http://127.0.0.1:${server.httpServer.address().port}/__ai_audit`);
  const input=page.locator('input[type=file]');
  await input.setInputFiles(process.env.H3_TEST_IMAGE || path.resolve('test/fixtures/upgrade-native-test.png'));
  const image=page.locator('.ai-selection-image img');await image.waitFor();
  await page.waitForFunction(()=>document.querySelector('.ai-selection-image img')?.naturalWidth>0);
  const box=await page.locator('.ai-selection-image').boundingBox();
  const imageBox=await image.boundingBox();
  assert.ok(Math.abs(box.width-imageBox.width)<1 && Math.abs(box.height-imageBox.height)<1, 'Selection coordinates must match the rendered image');
  await page.mouse.click(box.x+box.width*.4,box.y+box.height*.5);
  await page.getByRole('button',{name:'排除对象',exact:true}).click();
  await page.mouse.click(box.x+box.width*.8,box.y+box.height*.2);
  await page.getByRole('button',{name:'保留画笔',exact:true}).click();
  await page.mouse.move(box.x+box.width*.3,box.y+box.height*.4);await page.mouse.down();await page.mouse.move(box.x+box.width*.5,box.y+box.height*.6,{steps:8});await page.mouse.up();
  await page.getByRole('button',{name:'擦除画笔',exact:true}).click();
  await page.mouse.click(box.x+box.width*.2,box.y+box.height*.2);
  await page.getByRole('button',{name:'撤销',exact:true}).click();
  await page.locator('#toggle-ai-page').click();
  assert.equal(await page.locator('.ai-tools-page').isHidden(), true);
  await page.locator('#toggle-ai-page').click();
  assert.match(await page.locator('.ai-segment-summary').textContent(), /2 个点击 · 1 条笔画/);
  if(process.env.H3_TEST_SCREENSHOT) await page.screenshot({path:process.env.H3_TEST_SCREENSHOT,fullPage:true});
  await page.locator('.ai-run-button').click();
  await page.waitForFunction(()=>document.querySelector('.show-result'));
  const payload=await page.evaluate(()=>window.auditPayload);
  assert.equal(payload.segmentMode,'interactive');
  assert.equal(payload.segmentPrompts.points.length,2);
  assert.equal(payload.segmentPrompts.points[0].label,1);
  assert.equal(payload.segmentPrompts.points[1].label,0);
  assert.equal(payload.segmentPrompts.strokes.length,1);
  assert.ok(payload.segmentPrompts.strokes[0].points.length>1);
  await page.getByRole('button',{name:'返回编辑',exact:true}).click();
  await page.getByRole('button',{name:'框选对象',exact:true}).click();
  await page.mouse.move(box.x+box.width*.2,box.y+box.height*.2);await page.mouse.down();await page.mouse.move(box.x+box.width*.8,box.y+box.height*.8);await page.mouse.up();
  await page.locator('.ai-run-button').click();await page.waitForFunction(()=>document.querySelector('.show-result'));
  assert.ok(Math.abs((await page.evaluate(()=>window.auditPayload)).segmentPrompts.box.width-.6)<.05);
  await page.getByRole('button',{name:'清空选区',exact:true}).click();
  assert.match(await page.locator('.ai-segment-summary').textContent(),/0 个点击 · 0 条笔画/);
  await page.getByRole('button',{name:'自动去背景',exact:true}).click();await page.locator('.ai-run-button').click();await page.waitForFunction(()=>window.auditPayload.segmentMode==='automatic');
  await page.locator('#sidebar-understand').click();
  await page.waitForFunction(()=>!document.querySelector('.ai-selected-file'));
  assert.equal(await page.locator('.ai-answer').count(),0);assert.equal(await page.locator('.ai-selected-file').count(),0);
  await input.setInputFiles(path.resolve('test/fixtures/upgrade-native-test.png'));
  await page.evaluate(()=>window.answer=','.repeat(1500)+'测试');
  await page.locator('.ai-run-button').click();await page.locator('.ai-answer').waitFor();
  assert.equal(await page.locator('.ai-answer').evaluate(e=>e.scrollWidth<=e.clientWidth+1),true);
  await page.setViewportSize({width:1050,height:800});
  assert.equal(await page.locator('.ai-answer').evaluate(e=>e.scrollWidth<=e.clientWidth+1),true);
  await page.evaluate(()=>window.hold=true);await page.locator('.ai-run-button').click();
  await page.waitForFunction(()=>document.querySelector('input[type=file]').disabled);
  assert.equal(await input.isDisabled(),true);

  await page.evaluate(()=>{window.hold=false;window.finish();});
  await page.waitForFunction(()=>!document.querySelector('input[type=file]').disabled);
  assert.equal(await page.locator('.ai-tools-grid').count(),0,'Tool links belong only in the sidebar');
  await page.locator('#sidebar-image-enhance').click();
  assert.equal(await input.getAttribute('accept'),'image/*');
  await input.setInputFiles(path.resolve('test/fixtures/upgrade-native-test.png'));
  await page.locator('.ai-run-button').click();
  await page.locator('.ai-open-result').waitFor();
  assert.equal((await page.evaluate(()=>window.auditPayload)).kind,'image-enhance');
  assert.equal(await page.locator('img[alt="增强后的图片"]').count(),1);
  assert.deepEqual(errors,[]);
  console.log('AI browser passed: positive/negative clicks, brush strokes, undo, SAM box, transparent preview, clear/automatic, sidebar reset, long text wrapping, responsive layout and upload lock.');
} finally {await browser?.close();await server.close();}
