import assert from "node:assert/strict";
import fs from "node:fs";
import path from "node:path";
import vm from "node:vm";
import React from "react";
import { renderToStaticMarkup } from "react-dom/server";
import { createServer } from "vite";

const server = await createServer({ server: { middlewareMode: true }, appType: "custom" });
try {
  const { default: CutoutWorkspace } = await server.ssrLoadModule("/src/renderer/CutoutWorkspace.jsx");
  const props = { file: "", preview: "", history: [], engineReady: true, status: "本地引擎已就绪" };
  const render = (overrides = {}) => renderToStaticMarkup(React.createElement(CutoutWorkspace, { ...props, ...overrides }));
  const empty = render();
  assert.match(empty, /class="cutout-run" disabled=""/);
  assert.doesNotMatch(empty, /本次结果|本次完成后显示结果/);
  assert.doesNotMatch(empty, /cutout-upload-tile/);
  assert.doesNotMatch(empty, /最近生成|Prompt|<textarea|<video|时长/);
  const image = render({ file: "C:/portrait.png", preview: "file:///C:/portrait.png" });
  assert.match(image, /class="cutout-run">/);
  assert.match(image, /aria-label="替换图片"/);
  assert.match(image, /aria-label="移除图片"/);
  assert.match(render({ file: "portrait.png", preview: "file:///C:/portrait.png", busy: true }), /class="cutout-run" disabled=""/);
  assert.match(render({ file: "portrait.png", preview: "file:///C:/portrait.png", engineReady: false }), /class="cutout-run" disabled=""/);
  const completed = render({ history: [{ id: "test", originalName: "portrait.png", url: "file:///C:/result.png", size: 1048576, createdAt: Date.now() }] });
  assert.match(completed, /aria-label="预览 portrait\.png"/);
  assert.match(completed, /打开文件位置/);
  assert.match(completed, /aria-label="删除 portrait.png"/);
  assert.match(completed, /清空/);
  const missing = render({ history: [{ id: "missing", originalName: "gone.png", missingOutput: true, createdAt: Date.now() }] });
  assert.match(missing, /结果文件已移动或删除/);
  assert.match(missing, /class="cutout-history-preview[^"]*" disabled=""/);
  assert.doesNotMatch(missing, /<img/);
  assert.doesNotMatch(missing, /class="cutout-delete-button"[^>]*disabled/);
  assert.match(render({ history: [{ id: "test", originalName: "portrait.png", url: "file:///C:/result.png", size: 1048576, createdAt: Date.now() }], busy: true }), /title="清空全部抠图记录" disabled=""/);
  const noDuplicate = render({ recentResults: [], history: [{ id: "test", originalName: "portrait.png", url: "file:///C:/result.png", size: 1048576, createdAt: Date.now() }] });
  assert.doesNotMatch(noDuplicate, /本次结果|本次完成后显示结果/);
  assert.equal((noDuplicate.match(/aria-label="放大抠图结果"/g) || []).length, 0);
  const source = fs.readFileSync(new URL("../src/renderer/main.jsx", import.meta.url), "utf8");
  assert.match(source, /current\.id === "cutout" \? <CutoutWorkspace/);
  assert.match(source, /addPaths\(paths, current\.id === "cutout" \? files\.filter\(Boolean\)\.length : undefined\)/);
  assert.match(source, /window\.studio\.runCutoutBatch\?\.\(/);
  const main = fs.readFileSync(new URL("../src/main.cjs", import.meta.url), "utf8");
  assert.match(main, /async function runCutoutBatch\(/);
  assert.match(main, /ipcMain\.handle\("run-cutout-batch"/);
  assert.match(main, /ipcMain\.handle\("clear-cutouts"/);
  assert.match(main, /jobs\.filter\(\(job\) => job\.workflowId !== "cutout"\)/);
  const resolvePathCode = main.slice(main.indexOf("function defaultWorkflowPath("), main.indexOf("function readWorkflowConfig("));
  const context = { path, fs: { existsSync: () => false }, rootDir: () => "Z:/App", workflowFileName: () => "cutout.json", app: { isPackaged: true }, process: { resourcesPath: "Z:/bundle/resources" }, __dirname: "Z:/Source/src" };
  const resolveWorkflow = vm.runInNewContext(`${resolvePathCode}; defaultWorkflowPath`, context);
  assert.equal(resolveWorkflow("cutout"), path.join("Z:/bundle/resources", "workflows", "cutout.json"));
  context.fs.existsSync = () => true;
  assert.equal(resolveWorkflow("cutout"), path.join("Z:/App", "workflows", "cutout.json"));
  context.fs.existsSync = () => false;
  context.app.isPackaged = false;
  assert.equal(resolveWorkflow("cutout"), path.resolve("Z:/Source", "workflows", "cutout.json"));
  const cutoutWorkflow = new URL("../workflows/InspyrenetRembg抠图.json", import.meta.url);
  assert.equal(fs.existsSync(cutoutWorkflow), true, "The cutout workflow must ship with the source package");
  const portableBuilder = fs.readFileSync(new URL("../build_portable.ps1", import.meta.url), "utf8");
  assert.match(portableBuilder, /Copy-Item -LiteralPath \(\$workflowFiles\.FullName\)/);
  assert.match(portableBuilder, /Workflow manifest was not staged/);
  console.log("cutout UI checks passed");
} finally {
  await server.close();
}
